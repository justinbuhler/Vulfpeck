#!/usr/bin/env python3
"""Architecture decision records: one file per decision, kept in the repository.

An ADR is docs/adr/NNNN-slug.md (the directory is harness.toml `adr.dir`):

    # 0007. Lint before the session stops

    Status: accepted
    Date: 2026-10-22
    Components: .claude/hooks/session_guard.py, tests/test_session_guard.py
    Supersedes: 0004

    ## Context
    ## Decision
    ## Consequences
    ## Alternatives            (optional)

Status is one of proposed, accepted, rejected, deprecated, superseded. A
superseded ADR names its successor in `Superseded-by:`, and the successor names
it back in `Supersedes:`. `Components` are literal repository-relative paths, never globs.

Governed files (harness.toml `adr.require_for`, minus `adr.exempt`; empty by default)
must each be named by a proposed or accepted ADR: tests/test_adr.py fails the land
if any tracked governed file is uncovered. .claude/hooks/adr_gate.py is an optional
creation-time gate a project registers itself; this repository does not.

    python3 scripts/adr.py init                              # create the ADR directory
    python3 scripts/adr.py new "Title" --component PATH...   # next number, proposed
    python3 scripts/adr.py check [FILE...]                   # format, links, coverage
    python3 scripts/adr.py for PATH                          # ADRs that govern PATH
    python3 scripts/adr.py list
    python3 scripts/adr.py index                             # regenerate the README index
    python3 scripts/adr.py touched BASE HEAD                 # ADRs a change set touches

The dated index between the markers in docs/adr/README.md is generated; `check`
fails when it is stale. `touched` is what land.sh prints after a land: the ADRs
governing the files that moved, found through Components rather than guessed
from branch names.
"""
import argparse
import re
import subprocess
import sys
from datetime import date
from fnmatch import fnmatchcase
from pathlib import Path

STATUSES = ("proposed", "accepted", "rejected", "deprecated", "superseded")
COVERING = ("proposed", "accepted")
SECTIONS = ("Context", "Decision", "Consequences")
FIELDS = ("Status", "Date", "Components", "Supersedes", "Superseded-by")
NAME = re.compile(r"(\d{4})-[a-z0-9]+(?:-[a-z0-9]+)*\.md")
TITLE = re.compile(r"# (\d{4})\. (\S.*)")
FIELD = re.compile(r"([A-Z][A-Za-z-]*): *(.*)")
NUMBER = re.compile(r"\d{4}")
INDEX_START, INDEX_END = "<!-- adr-index:start (generated by scripts/adr.py index) -->", "<!-- adr-index:end -->"
TEMPLATE = """# {number}. {title}

Status: proposed
Date: {today}
Components: {components}

## Context

{context}

## Decision

{decision}

## Consequences

{consequences}
"""


GLOB_CHARS = set("*?[")
PLACEHOLDERS = {
    "Context": "What forces this decision: the problem, the constraints, what is true now.",
    "Decision": "What we will do, stated so a reviewer can check the code against it.",
    "Consequences": "What becomes easier, what becomes harder, and what this does not cover.",
}


def literal_problem(component):
    """Return why a component is not a literal repository path, or None.

    Components are literal paths, never globs: a decision names the files it
    governs. Every glob rule tried (a fixed first segment, probe names) was
    beaten by the next glob, so none is accepted.
    """
    if component.startswith("/") or ".." in component.split("/"):
        return "must be a relative path inside the repository"
    if GLOB_CHARS & set(component):
        return "must be a literal path, not a glob; list each file the decision governs"
    return None


def glob_match(pattern, path):
    """Return whether a repository-relative path matches a segment-aware glob.

    Case-insensitive: on a case-insensitive filesystem `.Claude/HOOKS/x.PY` is
    the same file as `.claude/hooks/x.py`, and matching more is the safe side.
    """
    pattern, path = pattern.lower(), path.lower()
    def match(p, s):
        if not p:
            return not s
        if p[0] == "**":
            return any(match(p[1:], s[i:]) for i in range(len(s) + 1))
        return bool(s) and fnmatchcase(s[0], p[0]) and match(p[1:], s[1:])
    return match(pattern.strip("/").split("/"), path.strip("/").split("/"))


def parse(path):
    """Return (record, problems) for one ADR file. A record is a dict."""
    problems = []
    try:
        text = Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return None, [f"{path}: unreadable: {exc}"]
    name = Path(path).name
    named = NAME.fullmatch(name)
    if not named:
        problems.append(f"{name}: file name must be NNNN-lowercase-slug.md")
    lines = text.splitlines()
    title = TITLE.fullmatch(lines[0].rstrip()) if lines else None
    if not title:
        problems.append(f"{name}: first line must be '# NNNN. Title'")
    elif named and title.group(1) != named.group(1):
        problems.append(f"{name}: heading number {title.group(1)} does not match the file name")
    record = {"path": Path(path), "number": named.group(1) if named else None,
              "title": title.group(2) if title else "", "components": [],
              "supersedes": [], "superseded_by": []}

    fields, body, section, sections = {}, lines[1:], None, {}
    for line in body:
        if line.startswith("## "):
            section = line[3:].strip()
            sections.setdefault(section, [])
            continue
        if section is None:
            found = FIELD.fullmatch(line.strip())
            if found and found.group(1) in FIELDS:
                if found.group(1) in fields:
                    problems.append(f"{name}: field {found.group(1)} given twice")
                fields[found.group(1)] = found.group(2).strip()
            elif found:
                problems.append(f"{name}: unknown field {found.group(1)!r}")
        else:
            sections[section].append(line)

    status = fields.get("Status", "").lower()
    record["status"] = status
    record["date"] = fields.get("Date", "")
    if status not in STATUSES:
        problems.append(f"{name}: Status must be one of {', '.join(STATUSES)} (got {fields.get('Status')!r})")
    try:
        date.fromisoformat(fields.get("Date", ""))
    except ValueError:
        problems.append(f"{name}: Date must be YYYY-MM-DD (got {fields.get('Date')!r})")
    components = [c.strip() for c in fields.get("Components", "").split(",") if c.strip()]
    for c in components:
        if literal_problem(c):
            problems.append(f"{name}: component {c!r} {literal_problem(c)}")
    record["components"] = components
    for key, out in (("Supersedes", "supersedes"), ("Superseded-by", "superseded_by")):
        refs = [r.strip() for r in fields.get(key, "").split(",") if r.strip()]
        bad = [r for r in refs if not NUMBER.fullmatch(r)]
        if bad:
            problems.append(f"{name}: {key} must list four-digit ADR numbers (got {bad})")
        record[out] = [r for r in refs if NUMBER.fullmatch(r)]
    if status == "superseded" and not record["superseded_by"]:
        problems.append(f"{name}: a superseded ADR must name its successor in Superseded-by")
    if record["superseded_by"] and status != "superseded":
        problems.append(f"{name}: Superseded-by is set but Status is {status!r}, not superseded")
    for heading in SECTIONS:
        if heading not in sections:
            problems.append(f"{name}: missing section '## {heading}'")
        elif not "".join(sections[heading]).strip():
            problems.append(f"{name}: section '## {heading}' is empty")
        elif " ".join("".join(sections[heading]).split()) == PLACEHOLDERS[heading]:
            problems.append(f"{name}: section '## {heading}' still holds the template text")
    return record, problems


def adr_files(adr_dir):
    """Return every ADR-shaped file in the directory (README and dotfiles excluded)."""
    if not Path(adr_dir).is_dir():
        return []
    return sorted(p for p in Path(adr_dir).glob("*.md")
                  if not p.name.startswith(".") and p.name.lower() != "readme.md")


def load_all(adr_dir):
    """Return (records, problems) for a whole ADR directory, links checked."""
    records, problems = [], []
    for path in adr_files(adr_dir):
        record, found = parse(path)
        problems += found
        if record:
            records.append(record)
    by_number = {}
    for r in records:
        if r["number"] in by_number:
            problems.append(f"{r['path'].name}: number {r['number']} is also used by "
                            f"{by_number[r['number']]['path'].name}")
        elif r["number"]:
            by_number[r["number"]] = r
    for r in records:
        for ref in r["superseded_by"]:
            other = by_number.get(ref)
            if other is None:
                problems.append(f"{r['path'].name}: Superseded-by {ref} does not exist")
            elif r["number"] not in other["supersedes"]:
                problems.append(f"{r['path'].name}: {ref} does not list {r['number']} in Supersedes")
        for ref in r["supersedes"]:
            other = by_number.get(ref)
            if other is None:
                problems.append(f"{r['path'].name}: Supersedes {ref} does not exist")
            elif r["number"] not in other["superseded_by"]:
                problems.append(f"{r['path'].name}: {ref} is not marked Superseded-by {r['number']}")
    return records, problems


def governed(config, rel):
    """Return whether a repository-relative path needs an ADR."""
    adr = config["adr"]
    if glob_match(adr["dir"].rstrip("/") + "/**", rel):
        return False
    return (any(glob_match(p, rel) for p in adr["require_for"])
            and not any(glob_match(p, rel) for p in adr["exempt"]))


def covering(records, rel):
    """Return the proposed or accepted ADRs whose Components name this path.

    Components are literal; one that is not (a glob, an escaping path) covers
    nothing. Case-insensitive, like governed().
    """
    rel = rel.strip("/").lower()
    return [r for r in records if r["status"] in COVERING
            and any(not literal_problem(c) and c.strip("/").lower() == rel for c in r["components"])]


def tracked(root):
    done = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, text=True)
    return [p for p in done.stdout.split("\0") if p] if done.returncode == 0 else []


def render_index(records):
    """Return the generated index lines: one dated line per decision."""
    lines = []
    for r in sorted(records, key=lambda r: r["number"] or ""):
        note = f" by {', '.join(r['superseded_by'])}" if r["superseded_by"] else ""
        lines.append(f"- {r['date']} — [{r['number']}. {r['title']}]({r['path'].name}) — {r['status']}{note}")
    return "\n".join(lines)


def index_problem(adr_dir, records):
    """Return a problem string when the README index is stale, else None."""
    readme = Path(adr_dir) / "README.md"
    if not readme.is_file():
        return ("README.md: the ADR index is missing (python3 scripts/adr.py init)"
                if records else None)
    text = readme.read_text(encoding="utf-8")
    if INDEX_START not in text or INDEX_END not in text:
        return "README.md: the ADR index markers are missing (python3 scripts/adr.py index)"
    current = text.split(INDEX_START, 1)[1].split(INDEX_END, 1)[0].strip()
    if current != render_index(records):
        return "README.md: the ADR index is stale (python3 scripts/adr.py index)"
    return None


def write_index(adr_dir, records):
    readme = Path(adr_dir) / "README.md"
    text = readme.read_text(encoding="utf-8") if readme.is_file() else "# Architecture decision records\n"
    block = f"{INDEX_START}\n{render_index(records)}\n{INDEX_END}"
    if INDEX_START in text and INDEX_END in text:
        head, rest = text.split(INDEX_START, 1)
        text = head + block + rest.split(INDEX_END, 1)[1]
    else:
        text = text.rstrip("\n") + "\n\n## Index\n\n" + block + "\n"
    readme.write_text(text, encoding="utf-8")


def touched(root, config, base, head):
    """Return [(record, [changed paths it governs])] for one change set."""
    done = subprocess.run(["git", "diff", "--name-only", f"{base}...{head}"], cwd=root,
                          capture_output=True, text=True)
    changed = [p for p in done.stdout.splitlines() if p] if done.returncode == 0 else []
    records, _ = load_all(Path(root) / config["adr"]["dir"])
    out = []
    for r in records:
        names = {c.strip("/").lower() for c in r["components"] if not literal_problem(c)}
        paths = [c for c in changed if c.lower() in names]
        rel = r["path"].relative_to(root).as_posix() if r["path"].is_relative_to(root) else ""
        if rel in changed:
            paths.insert(0, rel)
        if paths:
            out.append((r, paths))
    return out


README = """# Architecture decision records

One file per decision: `NNNN-slug.md`, created with `python3 scripts/adr.py new
"Decision" --component path`. The format and rules are in `scripts/adr.py`.
An author writes **proposed**; **accepted** is set by the reviewer. To change a
decision, write a new ADR with `Supersedes: NNNN` and mark the old one
`superseded` with `Superseded-by:`.
"""


def init(adr_dir):
    """Create the ADR directory and its README with an empty index; never overwrite."""
    adr_dir = Path(adr_dir)
    adr_dir.mkdir(parents=True, exist_ok=True)
    readme = adr_dir / "README.md"
    if not readme.exists():
        readme.write_text(README, encoding="utf-8")
    records, _ = load_all(adr_dir)
    text = readme.read_text(encoding="utf-8")
    if INDEX_START not in text:
        write_index(adr_dir, records)
    return readme


def check_repo(root, config):
    """Return every problem in the repository's ADRs and their coverage."""
    root = Path(root)
    adr_dir = root / config["adr"]["dir"]
    if not adr_dir.is_dir():
        if config["adr"]["require_for"]:
            return [f"{config['adr']['dir']}/: the ADR directory does not exist, and "
                    "adr.require_for governs files (python3 scripts/adr.py init)"]
    records, problems = load_all(root / config["adr"]["dir"])
    stale = index_problem(root / config["adr"]["dir"], records)
    if stale:
        problems.append(stale)
    files = tracked(root)
    for rel in files:
        if governed(config, rel) and (root / rel).exists() and not covering(records, rel):
            problems.append(f"{rel}: governed by adr.require_for but named by no proposed or "
                            f"accepted ADR (python3 scripts/adr.py new \"...\" --component {rel})")
    present = set(files)
    for r in records:
        if r["status"] != "accepted":
            continue
        for c in r["components"]:
            if not literal_problem(c) and c.lower() not in {f.lower() for f in present}:
                problems.append(f"{r['path'].name}: accepted ADR names {c!r}, which matches "
                                "no tracked file (stale: update Components, or deprecate it)")
    return problems


def next_number(adr_dir):
    numbers = [int(m.group(1)) for p in adr_files(adr_dir) if (m := NAME.fullmatch(p.name))]
    return f"{max(numbers, default=0) + 1:04d}"


def slug(title):
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60].strip("-") or "decision"


def repo_root(start):
    done = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=start,
                          capture_output=True, text=True)
    return Path(done.stdout.strip()) if done.returncode == 0 else Path(start).resolve()


def load_config(root):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import harness_config
    return harness_config.load(root)


def main(argv=None):
    parser = argparse.ArgumentParser(prog="adr", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("init", help="create the ADR directory and README index")
    p = sub.add_parser("new", help="write the next-numbered ADR as proposed")
    p.add_argument("title")
    p.add_argument("--component", action="append", default=[])
    p = sub.add_parser("check", help="validate ADRs; with no FILE, also coverage")
    p.add_argument("files", nargs="*")
    p = sub.add_parser("for", help="list the ADRs that govern a path")
    p.add_argument("path")
    sub.add_parser("list", help="list every ADR")
    sub.add_parser("index", help="regenerate the dated index in the ADR README")
    p = sub.add_parser("touched", help="list the ADRs governing files changed in BASE...HEAD")
    p.add_argument("base")
    p.add_argument("head")
    args = parser.parse_args(argv)

    root = repo_root(Path.cwd())
    config = load_config(root)
    adr_dir = root / config["adr"]["dir"]

    if args.command == "init":
        print(init(adr_dir).relative_to(root))
        return 0
    if args.command == "new":
        if not adr_dir.is_dir():
            init(adr_dir)
        number = next_number(adr_dir)
        path = adr_dir / f"{number}-{slug(args.title)}.md"
        adr_dir.mkdir(parents=True, exist_ok=True)
        path.write_text(TEMPLATE.format(number=number, title=args.title.strip(),
                                        today=date.today().isoformat(),
                                        components=", ".join(args.component),
                                        **{k.lower(): v for k, v in PLACEHOLDERS.items()}))
        print(path.relative_to(root))
        return 0
    if args.command == "check":
        if args.files:
            problems = [p for f in args.files for p in parse(f)[1]]
        else:
            problems = check_repo(root, config)
        for line in problems:
            print(line, file=sys.stderr)
        print(f"adr: {len(adr_files(adr_dir))} record(s), {len(problems)} problem(s)")
        return 1 if problems else 0
    if args.command == "touched":
        root = root.resolve()
        for r, paths in touched(root, config, args.base, args.head):
            shown = ", ".join(paths[:4]) + (f" (+{len(paths) - 4})" if len(paths) > 4 else "")
            print(f"ADR {r['number']} [{r['status']}] {r['title']}: {shown}")
        return 0
    records, problems = load_all(adr_dir)
    if args.command == "index":
        write_index(adr_dir, records)
        print((adr_dir / "README.md").relative_to(root))
        return 0
    if args.command == "for":
        rel = Path(args.path).resolve().relative_to(root).as_posix() if Path(args.path).is_absolute() else args.path
        for r in covering(records, rel):
            print(f"{r['number']}  {r['status']:<10} {r['title']}")
        return 0
    for r in records:
        print(f"{r['number']}  {r['status']:<10} {r['title']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
